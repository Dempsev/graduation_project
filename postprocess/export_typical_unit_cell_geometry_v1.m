function export_typical_unit_cell_geometry_v1()
% Export a representative COMSOL-built unit-cell geometry with thesis-style layout.

import com.comsol.model.*
import com.comsol.model.util.*

thisDir = fileparts(mfilename('fullpath'));
rootDir = fileparts(thisDir);
addpath(genpath(fullfile(rootDir, 'model_core')));
addpath(genpath(fullfile(rootDir, 'stage2_harmonics')));
addpath(genpath(fullfile(rootDir, 'stage2_harmonics_refine')));
addpath(genpath(fullfile(rootDir, 'stage4_validation')));

sourceCsv = fullfile(rootDir, 'data', 'analysis', 'canonical_local_robustness_v1', 'canonical_local_robustness_merged_v1.csv');
sampleId = 'stage4_validation_targetband_local_robustness_v1_band200_240_ep193_center';
outPath = fullfile(rootDir, 'data', 'analysis', 'thesis_ch3_v1', 'figures', 'figure_3_0_typical_unit_cell.png');

if ~isfile(sourceCsv)
    error('export_typical_unit_cell_geometry_v1:MissingSourceCsv', ...
        'Merged robustness csv not found: %s', sourceCsv);
end

rows = readtable(sourceCsv);
rows = rows(strcmp(string(rows.sample_id), sampleId), :);
if isempty(rows)
    error('export_typical_unit_cell_geometry_v1:MissingSampleRow', ...
        'Sample row not found: %s', sampleId);
end

row = rows(1, :);
shapeId = char(string(pick_text(row, {'shape_id', 'shape_id_x', 'shape_id_y'})));
shapeFile = fullfile(rootDir, 'data', 'shape_contours', [shapeId '.csv']);
if ~isfile(shapeFile)
    error('export_typical_unit_cell_geometry_v1:MissingShapeFile', ...
        'Shape contour not found: %s', shapeFile);
end

cfg = get_stage4_validation_config_targetband_local_robustness_v1();
pointSpec = build_point_spec_from_row(row);

[report, model] = validate_stage2_harmonics_geometry(cfg, pointSpec, shapeFile, sampleId);
if isempty(model) || ~report.geometry_valid
    error('export_typical_unit_cell_geometry_v1:GeometryBuildFailed', ...
        'COMSOL geometry build failed for %s: %s', sampleId, char(string(report.error_message)));
end

export_geometry_figure(model, outPath, shapeFile);

try
    ModelUtil.clear;
catch
end

fprintf('Exported unit-cell geometry: %s\n', outPath);
end

function pointSpec = build_point_spec_from_row(row)
pointSpec = struct( ...
    'main_id', pick_text(row, {'main_id'}), ...
    'point_id', pick_text(row, {'point_id'}), ...
    'a1', pick_numeric(row, {'a1_y', 'a1_x', 'a1'}), ...
    'a2', pick_numeric(row, {'a2_y', 'a2_x', 'a2'}), ...
    'b1', pick_numeric(row, {'b1'}), ...
    'b2', pick_numeric(row, {'b2_y', 'b2_x', 'b2'}), ...
    'r0', pick_numeric(row, {'r0_y', 'r0_x', 'r0'}), ...
    'a3', pick_numeric(row, {'a3'}), ...
    'b3', pick_numeric(row, {'b3'}), ...
    'a4', pick_numeric(row, {'a4'}), ...
    'b4', pick_numeric(row, {'b4'}), ...
    'a5', pick_numeric(row, {'a5'}), ...
    'b5', pick_numeric(row, {'b5'}) ...
);
end

function value = pick_numeric(row, fieldNames)
value = NaN;
for i = 1:numel(fieldNames)
    name = fieldNames{i};
    if ismember(name, row.Properties.VariableNames)
        raw = row.(name)(1);
        if isstring(raw) || ischar(raw)
            num = str2double(string(raw));
        else
            num = double(raw);
        end
        if isfinite(num)
            value = num;
            return;
        end
    end
end
end

function value = pick_text(row, fieldNames)
value = "";
for i = 1:numel(fieldNames)
    name = fieldNames{i};
    if ismember(name, row.Properties.VariableNames)
        value = string(row.(name)(1));
        if strlength(value) > 0
            return;
        end
    end
end
end

