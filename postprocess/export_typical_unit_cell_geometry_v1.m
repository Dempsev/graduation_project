function value = eval_param(model, expr, fallback)
value = fallback;
try
    value = model.param.evaluate(expr);
    if ischar(value) || isstring(value)
        value = str2double(value);
    end
catch
end
if ~isfinite(value)
    value = fallback;
end

end
