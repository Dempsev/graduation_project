    'stage4_validation_contactaware_highfreq_pilot_v1', ...
    validationDir, ...
    'contactaware_highfreq_manifest_v1.csv', ...
    'contactaware_highfreq_manifest_summary_v1.json', ...
    outDir);
cfg.shapeDir = fullfile(rootDir, 'data', 'contactaware_highfreq_pilot_v1', 'shape_contours');
end
